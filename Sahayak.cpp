/* Calculate priority of the problem */
void Problem::calculatePriority()
{
    if (category == "Other")
    {
        priority = "Not Available";

        cout << "\nPriority      : " << priority << endl;
        return;
    }

    if (category == "Health" ||
        category == "Road" ||
        category == "Electricity" ||
        category == "Water")
    {
        priority = "High";
    }

    else if (category == "Waste & Cleanliness" ||
             category == "Environment" ||
             category == "Transport")
    {
        priority = "Medium";
    }

    else
    {
        priority = "Normal";
    }

    cout << "\nPriority      : " << priority << endl;
}

/* Feedback from user */
void Problem::getFeedback()
{
    int choice;

    if (status == "Unresolved")
        return;

    cout << "\n========== GUIDANCE FEEDBACK ==========\n";
    cout << "Was this guidance helpful?\n";
    cout << "1. Yes\n";
    cout << "2. No\n";
    cout << "Enter your choice: ";
    cin >> choice;

    if (choice == 1)
    {
        status = "Resolved";

        cout << "\nThank you for your feedback!\n";
        cout << "Problem status: Resolved\n";
    }

    else if (choice == 2)
    {
        status = "Unresolved";

        cout << "\nProblem status: Unresolved\n";
        cout << "You can try describing the problem differently or choose another category.\n";
    }

    else
    {
        cout << "\nInvalid feedback choice.\n";
    }
}

/* Display final problem information */
void Problem::showProblem()
{
    cout << "\n========== PROBLEM SUMMARY ==========\n";

    cout << "Problem ID  : " << problemId << endl;
    cout << "Area Type   : " << areaType << endl;

    if (areaType == "Urban" || areaType == "urban")
    {
        cout << "Ward        : " << ward << endl;
        cout << "Municipality: " << municipality << endl;
    }

    cout << "Problem     : " << description << endl;
    cout << "Category    : " << category << endl;
    cout << "Priority    : " << priority << endl;
    cout << "Status      : " << status << endl;

    cout << "=====================================\n";

    /* SAVE RECORD */

    ofstream file("sahayak_records.txt", ios::app);

    if (file)
    {
        file << "\n========== PROBLEM RECORD ==========\n";

        file << "Problem ID   : " << problemId << endl;
        file << "Area Type    : " << areaType << endl;

        if (areaType == "Urban" || areaType == "urban")
        {
            file << "Ward         : " << ward << endl;
            file << "Municipality : " << municipality << endl;
        }

        file << "Problem      : " << description << endl;
        file << "Category     : " << category << endl;
        file << "Priority     : " << priority << endl;
        file << "Status       : " << status << endl;

        file << "=====================================\n";

        file.close();

        cout << "\nRecord saved successfully!\n";
    }
    else
    {
        cout << "\nError: Record could not be saved.\n";
    }
}

/* Main function */
int main()
{
    Problem p;
    int choice;

    cout << "\n============================================\n";
    cout << "       SAHAYAK - PUBLIC PROBLEM GUIDE\n";
    cout << "============================================\n";

    do
    {
        cout << "\n============== MAIN MENU ==============\n";
        cout << "1. Get Help\n";
        cout << "2. Exit\n";
        cout << "Enter your choice: ";
        cin >> choice;

        switch (choice)
        {
            case 1:

                p.inputProblem();

                p.selectInputMethod();

                p.showGuidance();

                p.calculatePriority();

                p.getFeedback();

                p.showProblem();

                break;

            case 2:

                cout << "\nThank you for using SAHAYAK!\n";

                break;

            default:

                cout << "\nInvalid choice. Please try again.\n";
        }

    } while (choice != 2);

    return 0;
}