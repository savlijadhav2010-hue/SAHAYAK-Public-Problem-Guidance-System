#include <iostream>
#include <string>
#include <cctype>
#include <fstream>

using namespace std;

class Problem
{
private:
    int problemId;
    string areaType;
    string municipality;
    string ward;

    string description;
    string category;
    string solution;
    string helper;
    string place;
    string information;
    string status;
    string priority;

public:
    void inputProblem();
    void selectInputMethod();
    void identifyCategory();
    void chooseCategory();
    void showGuidance();
    void calculatePriority();
    void getFeedback();
    void showProblem();
};

/* Enter basic problem details */
void Problem::inputProblem()
{
    int nextProblemId = 1001;

    // Read the last ID from the file
    ifstream file("last_id.txt");

    if (file)
    {
        file >> nextProblemId;
        file.close();
    }

    problemId = nextProblemId;

    // Save the next ID for the next user
    ofstream outfile("last_id.txt");

    if (outfile)
    {
        outfile << nextProblemId + 1;
        outfile.close();
    }

    cout << "\nProblem ID generated by SAHAYAK: "
         << problemId << endl;

    cout << "Enter Area Type (Rural/Urban): ";
    cin >> areaType;

    if (areaType == "Urban" || areaType == "urban")
    {
        cout << "Enter Ward Number: ";
        cin >> ward;

        // Ward to Municipality mapping
        if (ward == "1")
        {
            municipality = "Municipality A";
        }
        else if (ward == "2")
        {
            municipality = "Municipality A";
        }
        else if (ward == "3")
        {
            municipality = "Municipality B";
        }
        else if (ward == "4")
        {
            municipality = "Municipality B";
        }
        else
        {
            municipality = "Other Municipality";
        }

        cout << "Municipality: " << municipality << endl;
    }
    else
    {
        cout << "Rural area selected." << endl;
    }
}

/* Choose how the user wants to get help */
void Problem::selectInputMethod()
{
    int choice;

    cout << "\n========== HOW DO YOU WANT TO GET HELP? ==========\n";
    cout << "1. Write my problem\n";
    cout << "2. Choose a category\n";
    cout << "Enter your choice: ";
    cin >> choice;

    if (choice == 1)
    {
        cin.ignore();

        cout << "\nDescribe your problem: ";
        getline(cin, description);

        identifyCategory();
    }
    else if (choice == 2)
    {
        chooseCategory();
    }
    else
    {
        cout << "\nInvalid choice. Please try again.\n";
        category = "Other";
        status = "Unresolved";
    }
}

/* Identify category using simple keyword matching */
void Problem::identifyCategory()
{
    string text = description;

    for (char &c : text)
    {
        c = static_cast<char>(
            tolower(static_cast<unsigned char>(c))
        );
    }

    /* Property/House Tax is checked before Housing */

    if (text.find("property tax") != string::npos ||
        text.find("house tax") != string::npos ||
        text.find("ghar tax") != string::npos ||
        text.find("gharpatty") != string::npos ||
        text.find("ghar patti") != string::npos ||
        text.find("tax payment") != string::npos)
    {
        category = "Property & House Tax";
    }

    else if (text.find("water") != string::npos ||
             text.find("pani") != string::npos ||
             text.find("tap") != string::npos)
    {
        category = "Water";
    }

    else if (text.find("waste") != string::npos ||
             text.find("garbage") != string::npos ||
             text.find("dustbin") != string::npos ||
             text.find("kachra") != string::npos)
    {
        category = "Waste & Cleanliness";
    }

    else if (text.find("electricity") != string::npos ||
             text.find("electric") != string::npos ||
             text.find("light") != string::npos ||
             text.find("bijli") != string::npos)
    {
        category = "Electricity";
    }

    else if (text.find("road") != string::npos ||
             text.find("rasta") != string::npos ||
             text.find("pothole") != string::npos)
    {
        category = "Road";
    }

    else if (text.find("hospital") != string::npos ||
             text.find("doctor") != string::npos ||
             text.find("health") != string::npos ||
             text.find("medical") != string::npos)
    {
        category = "Health";
    }

    else if (text.find("school") != string::npos ||
             text.find("college") != string::npos ||
             text.find("education") != string::npos ||
             text.find("student") != string::npos)
    {
        category = "Education";
    }

    else if (text.find("aadhaar") != string::npos ||
             text.find("aadhar") != string::npos ||
             text.find("certificate") != string::npos ||
             text.find("document") != string::npos ||
             text.find("government") != string::npos)
    {
        category = "Government Services & Documents";
    }

    else if (text.find("farmer") != string::npos ||
             text.find("farming") != string::npos ||
             text.find("crop") != string::npos ||
             text.find("agriculture") != string::npos ||
             text.find("kisan") != string::npos)
    {
        category = "Agriculture";
    }

    else if (text.find("job") != string::npos ||
             text.find("employment") != string::npos ||
             text.find("work") != string::npos)
    {
        category = "Employment";
    }

    else if (text.find("bus") != string::npos ||
             text.find("transport") != string::npos ||
             text.find("vehicle") != string::npos)
    {
        category = "Transport";
    }

    else if (text.find("online") != string::npos ||
             text.find("internet") != string::npos ||
             text.find("digital") != string::npos ||
             text.find("app") != string::npos)
    {
        category = "Digital Services";
    }

    else if (text.find("pollution") != string::npos ||
             text.find("environment") != string::npos ||
             text.find("tree") != string::npos)
    {
        category = "Environment";
    }

    else if (text.find("product") != string::npos ||
             text.find("shop") != string::npos ||
             text.find("refund") != string::npos ||
             text.find("consumer") != string::npos)
    {
        category = "Consumer Problem";
    }

    else if (text.find("house") != string::npos ||
             text.find("housing") != string::npos ||
             text.find("home") != string::npos)
    {
        category = "Housing";
    }

    else
    {
        category = "Other";
    }
}

